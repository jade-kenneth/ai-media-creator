#!/usr/bin/env node
// Generates the technical catalogs under docs/catalogs/ from source.
//
// Hand-maintained catalogs drift the moment someone is in a hurry, and a stale
// catalog is worse than none: an agent navigating a large codebase by an
// inaccurate index reaches a confident wrong conclusion. These are regenerated
// from the code and verified in CI, so they can be trusted as a starting point.
//
// Parsing is pattern-based over TypeScript source rather than AST-based. That
// is sufficient for an index whose job is to point at a file and line — every
// entry cites its source location so the code stays the source of truth.
//
// Usage:
//   node scripts/generate-catalogs.mjs           write docs/catalogs/
//   node scripts/generate-catalogs.mjs --check   fail if regeneration differs

import {
  readFileSync,
  writeFileSync,
  readdirSync,
  existsSync,
  mkdirSync,
  statSync,
} from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = 'docs/catalogs';
const API_SRC = 'apps/app-api/src';

const checkOnly = process.argv.includes('--check');

const BANNER = (title, description) =>
  `<!-- Generated by scripts/generate-catalogs.mjs — do not edit by hand. -->\n` +
  `# ${title}\n\n${description}\n\n` +
  `Regenerate with \`npm run catalogs\`. CI fails when this file does not match source.\n\n`;

// ── helpers ──────────────────────────────────────────────────────────────────

function read(path) {
  try {
    return readFileSync(join(root, path), 'utf8');
  } catch {
    return '';
  }
}

function walk(path, extension = '.ts') {
  const absolute = join(root, path);

  if (!existsSync(absolute)) return [];

  const files = [];

  for (const entry of readdirSync(absolute, { withFileTypes: true })) {
    const child = join(path, entry.name);

    if (entry.isDirectory()) {
      files.push(...walk(child, extension));
    } else if (
      entry.name.endsWith(extension) &&
      !entry.name.endsWith('.spec.ts')
    ) {
      files.push(child);
    }
  }

  return files.sort();
}

function lineOf(source, index) {
  return source.slice(0, index).split('\n').length;
}

function table(headers, rows) {
  if (rows.length === 0) return '_None found._\n';

  const head = `| ${headers.join(' | ')} |`;
  const rule = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((row) => `| ${row.join(' | ')} |`).join('\n');

  return `${head}\n${rule}\n${body}\n`;
}

function code(value) {
  return value ? `\`${value}\`` : '—';
}

/** Loads the tenant classification so catalogs can show it alongside each collection. */
function tenantManifest() {
  try {
    return JSON.parse(read('tenant-scope.config.json'));
  } catch {
    return { modules: {} };
  }
}

// ── REST endpoints and webhooks ──────────────────────────────────────────────

const HTTP_METHODS = [
  'Get',
  'Post',
  'Put',
  'Patch',
  'Delete',
  'Head',
  'Options',
];

function collectRestEndpoints() {
  const endpoints = [];

  for (const file of walk(API_SRC)) {
    const source = read(file);
    const controller = source.match(/@Controller\((?:'([^']*)'|"([^"]*)")?\)/);

    if (!controller) continue;

    const basePath = controller[1] ?? controller[2] ?? '';
    const controllerIsPublic = /@Controller\([^)]*\)\s*@Public\(\)/.test(
      source,
    );

    const pattern = new RegExp(
      `@(${HTTP_METHODS.join('|')})\\((?:'([^']*)'|"([^"]*)")?\\)([\\s\\S]{0,400}?)\\n\\s*(?:async\\s+)?(\\w+)\\s*\\(`,
      'g',
    );

    for (const match of source.matchAll(pattern)) {
      const [, method, singleQuoted, doubleQuoted, between, handler] = match;
      const subPath = singleQuoted ?? doubleQuoted ?? '';
      const fullPath = `/${[basePath, subPath].filter(Boolean).join('/')}`;

      endpoints.push({
        method: method.toUpperCase(),
        path: fullPath,
        handler,
        public: controllerIsPublic || between.includes('@Public()'),
        file,
        line: lineOf(source, match.index),
      });
    }
  }

  return endpoints.sort(
    (a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method),
  );
}

/**
 * A webhook is an unauthenticated POST that verifies a provider signature or
 * token instead of a session — the property that makes it externally callable.
 */
function isWebhook(endpoint, source) {
  if (endpoint.method !== 'POST' || !endpoint.public) return false;

  return (
    /webhook|callback|notification/i.test(endpoint.path) ||
    /verifyCallbackToken|@Headers\(['"]x-[a-z-]*(signature|token)/i.test(source)
  );
}

// ── GraphQL operations ───────────────────────────────────────────────────────

/**
 * Decorators applied to the class, which every handler in it inherits. Missing
 * these reports a guarded operation as unguarded — a false security signal, and
 * the precise way a catalog becomes worse than no catalog.
 */
function classLevelDecorators(source) {
  const declaration = source.search(/^export class /m);
  const head = declaration === -1 ? source : source.slice(0, declaration);

  return {
    guard: head.match(/@UseGuards\(([^)]+)\)/)?.[1].trim() ?? '',
    roles:
      head
        .match(/@Roles\(([^)]+)\)/)?.[1]
        .replace(/UserRole\./g, '')
        .trim() ?? '',
  };
}

function collectGraphqlOperations() {
  const operations = [];

  for (const file of walk(API_SRC)) {
    const source = read(file);

    if (!source.includes('@Resolver')) continue;

    const inherited = classLevelDecorators(source);
    const pattern =
      /@(Query|Mutation|Subscription)\((?:'([^']*)'|"([^"]*)")?\)([\s\S]{0,400}?)\n\s*(?:async\s+)?(\w+)\s*\(/g;

    for (const match of source.matchAll(pattern)) {
      const [, kind, singleQuoted, doubleQuoted, between, handler] = match;
      const guard = between.match(/@UseGuards\(([^)]+)\)/);
      const roles = between.match(/@Roles\(([^)]+)\)/);
      const isPublic = between.includes('@Public()');

      // Parameter decorators sit after the handler name, not between the
      // method decorator and it, so they need their own window.
      const parameterList = source.slice(
        match.index + match[0].length,
        match.index + match[0].length + 500,
      );
      const parameters = parameterList.slice(0, parameterList.indexOf('):'));

      operations.push({
        kind,
        name: singleQuoted ?? doubleQuoted ?? handler,
        handler,
        guard: isPublic ? '' : guard ? guard[1].trim() : inherited.guard,
        roles: roles
          ? roles[1].replace(/UserRole\./g, '').trim()
          : inherited.roles,
        inherited: !guard && Boolean(inherited.guard) && !isPublic,
        public: isPublic,
        tenantAware: parameters.includes('@CurrentTenant'),
        file,
        line: lineOf(source, match.index),
      });
    }
  }

  return operations.sort(
    (a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name),
  );
}

// ── Collections ──────────────────────────────────────────────────────────────

function collectCollections() {
  const manifest = tenantManifest();
  const collections = [];

  for (const file of walk(API_SRC).filter((f) =>
    f.endsWith('.repository.ts'),
  )) {
    const source = read(file);
    // Model name is always the second constructor argument, but the constructor
    // may be MongooseRepository directly or a subclass of it, and the call may
    // be a `new` or a `super`. Match on the (connection, 'Name') shape instead
    // of on the class, so a new subclass does not silently drop its collection
    // out of the catalog.
    const model =
      source.match(/new\s+\w+(?:<[^>]*>)?\(\s*connection,\s*'([^']+)'/) ??
      source.match(/super\(\s*connection,\s*'([^']+)'/);

    if (!model) continue;

    const moduleName = file.match(/modules\/([^/]+)\//)?.[1] ?? '';
    const declaration = manifest.modules?.[moduleName] ?? {};
    const indexes = [
      ...source.matchAll(/\[\s*\{([^}]+)\}\s*(?:,\s*\{([^}]*)\})?\s*\]/g),
    ]
      .map(([, keys, options]) => {
        const fields = keys
          .split(',')
          .map((part) => part.split(':')[0].trim())
          .filter(Boolean)
          .join(', ');

        return options?.includes('unique') ? `${fields} (unique)` : fields;
      })
      .filter(Boolean);

    collections.push({
      model: model[1],
      module: moduleName,
      scope: declaration.scope ?? 'undeclared',
      indexes,
      file,
      line: lineOf(source, model.index),
    });
  }

  return collections.sort((a, b) => a.model.localeCompare(b.model));
}

// ── Scheduled work ───────────────────────────────────────────────────────────

function collectScheduledWork() {
  const jobs = [];

  for (const file of walk(API_SRC)) {
    const source = read(file);
    const pattern =
      /@(Cron|Interval|Timeout)\(([^)]*)\)([\s\S]{0,300}?)\n\s*(?:async\s+)?(\w+)\s*\(/g;

    for (const match of source.matchAll(pattern)) {
      const [, kind, argument, between, handler] = match;

      jobs.push({
        kind,
        schedule: argument.split(',')[0].trim().replace(/['"]/g, ''),
        handler,
        locked:
          /withLock|acquire\(/.test(between) ||
          /withLock|acquire\(/.test(source),
        file,
        line: lineOf(source, match.index),
      });
    }
  }

  return jobs.sort((a, b) => a.handler.localeCompare(b.handler));
}

// ── Environment variables ────────────────────────────────────────────────────

function collectEnvVars() {
  const source = read(`${API_SRC}/config/env.schema.ts`);
  const objectStart = source.indexOf('z\n  .object({');
  const body = objectStart === -1 ? source : source.slice(objectStart);
  const variables = [];

  // Keys are declared at a single indent level inside the schema object.
  for (const match of body.matchAll(
    /\n {4}([A-Z][A-Z0-9_]*):\s*([\s\S]*?)(?=\n {4}[A-Z][A-Z0-9_]*:|\n {2}\}\))/g,
  )) {
    const [, name, definition] = match;
    const defaultValue = definition.match(/\.default\(([^)]*)\)/);
    const isOptional =
      definition.includes('.optional()') || Boolean(defaultValue);

    let type = 'string';
    if (/z\.coerce\.number|z\.number/.test(definition)) type = 'number';
    if (/z\.boolean|normalizeBooleanEnv/.test(definition)) type = 'boolean';
    if (/z\.enum/.test(definition)) {
      type = `enum(${definition.match(/z\.enum\(\[([^\]]*)\]/)?.[1].replace(/['"]/g, '') ?? ''})`;
    }

    variables.push({
      name,
      type,
      required: !isOptional,
      default: defaultValue ? defaultValue[1].trim().replace(/['"]/g, '') : '',
      line: lineOf(source, source.indexOf(`\n    ${name}:`)) + 1,
    });
  }

  // Cross-check against .env.example so a documented-but-unvalidated variable
  // (or the reverse) is visible rather than silently diverging.
  const exampleKeys = new Set(
    read('.env.example')
      .split('\n')
      .map((line) => line.match(/^([A-Z][A-Z0-9_]*)=/)?.[1])
      .filter(Boolean),
  );

  const schemaKeys = new Set(variables.map((variable) => variable.name));

  return {
    variables: variables.sort((a, b) => a.name.localeCompare(b.name)),
    missingFromExample: [...schemaKeys]
      .filter((key) => !exampleKeys.has(key))
      .sort(),
    missingFromSchema: [...exampleKeys]
      .filter((key) => !schemaKeys.has(key))
      .sort(),
  };
}

// ── Render ───────────────────────────────────────────────────────────────────

function renderEndpoints() {
  const endpoints = collectRestEndpoints();
  const webhooks = [];
  const plain = [];

  for (const endpoint of endpoints) {
    (isWebhook(endpoint, read(endpoint.file)) ? webhooks : plain).push(
      endpoint,
    );
  }

  const graphql = collectGraphqlOperations();

  let doc = BANNER(
    'Endpoint catalog',
    'Every HTTP route and GraphQL operation the API exposes, with its auth posture.',
  );

  doc += `## REST endpoints\n\n`;
  doc += table(
    ['Method', 'Path', 'Handler', 'Auth', 'Source'],
    plain.map((endpoint) => [
      endpoint.method,
      code(endpoint.path),
      code(endpoint.handler),
      endpoint.public ? '**public**' : 'guarded',
      `${endpoint.file}:${endpoint.line}`,
    ]),
  );

  doc += `\n## Webhooks\n\nExternally callable, unauthenticated by session, and authenticated instead by a provider signature or token. Each must be idempotent on redelivery.\n\n`;
  doc += table(
    ['Method', 'Path', 'Handler', 'Source'],
    webhooks.map((endpoint) => [
      endpoint.method,
      code(endpoint.path),
      code(endpoint.handler),
      `${endpoint.file}:${endpoint.line}`,
    ]),
  );

  doc += `\n## GraphQL operations\n\n`;
  doc += table(
    ['Kind', 'Name', 'Guard', 'Roles', 'Tenant-aware', 'Source'],
    graphql.map((operation) => [
      operation.kind,
      code(operation.name),
      operation.guard
        ? `${code(operation.guard)}${operation.inherited ? ' _(class)_' : ''}`
        : operation.public
          ? '**@Public**'
          : '**none**',
      operation.roles || '—',
      operation.tenantAware ? 'yes' : 'no',
      `${operation.file}:${operation.line}`,
    ]),
  );

  return doc;
}

function renderCollections() {
  const collections = collectCollections();

  let doc = BANNER(
    'Collection catalog',
    'MongoDB collections, their owning module, tenant classification, and indexes. ' +
      'Scope comes from `tenant-scope.config.json` and is enforced by `npm run check-tenant-scope`.',
  );

  doc += table(
    ['Collection', 'Module', 'Tenant scope', 'Indexes', 'Source'],
    collections.map((collection) => [
      code(collection.model),
      collection.module,
      collection.scope === 'tenant-scoped'
        ? '**tenant-scoped**'
        : collection.scope,
      collection.indexes.length
        ? collection.indexes.map((index) => `\`${index}\``).join('<br>')
        : '—',
      `${collection.file}:${collection.line}`,
    ]),
  );

  return doc;
}

function renderJobs() {
  const jobs = collectScheduledWork();

  let doc = BANNER(
    'Scheduled work catalog',
    'Cron jobs, intervals, and timeouts. Every recurring job must acquire a scheduler lock ' +
      'before doing work, or it double-fires across replicas.',
  );

  doc += table(
    ['Kind', 'Schedule', 'Handler', 'Lock acquired', 'Source'],
    jobs.map((job) => [
      job.kind,
      code(job.schedule),
      code(job.handler),
      job.locked ? 'yes' : '**no**',
      `${job.file}:${job.line}`,
    ]),
  );

  return doc;
}

function renderEnv() {
  const { variables, missingFromExample, missingFromSchema } = collectEnvVars();

  let doc = BANNER(
    'Environment variable catalog',
    'Parsed from `apps/app-api/src/config/env.schema.ts`, the single validated source. ' +
      'Values are never recorded here — only names, types, and whether a default exists.',
  );

  doc += table(
    ['Variable', 'Type', 'Required', 'Default'],
    variables.map((variable) => [
      code(variable.name),
      variable.type,
      variable.required ? '**yes**' : 'no',
      variable.default ? code(variable.default) : '—',
    ]),
  );

  if (missingFromExample.length > 0) {
    doc += `\n## Validated but absent from \`.env.example\`\n\nA new environment cannot be configured from the example file alone.\n\n`;
    doc += missingFromExample.map((key) => `- \`${key}\``).join('\n') + '\n';
  }

  if (missingFromSchema.length > 0) {
    doc += `\n## In \`.env.example\` but not validated\n\nThese are read without schema validation, or are stale entries.\n\n`;
    doc += missingFromSchema.map((key) => `- \`${key}\``).join('\n') + '\n';
  }

  return doc;
}

// ── Write or check ───────────────────────────────────────────────────────────

const outputs = {
  'endpoints.md': renderEndpoints(),
  'collections.md': renderCollections(),
  'jobs.md': renderJobs(),
  'environment.md': renderEnv(),
};

if (checkOnly) {
  const stale = [];

  for (const [name, content] of Object.entries(outputs)) {
    if (read(join(OUT_DIR, name)) !== content) {
      stale.push(name);
    }
  }

  if (stale.length > 0) {
    console.error(
      `✗ Catalogs are out of date: ${stale.join(', ')}\n` +
        '  The code changed without regenerating its index. Run: npm run catalogs',
    );
    process.exit(1);
  }

  console.log(
    `✓ Catalogs match source (${Object.keys(outputs).length} files).`,
  );
  process.exit(0);
}

mkdirSync(join(root, OUT_DIR), { recursive: true });

for (const [name, content] of Object.entries(outputs)) {
  writeFileSync(join(root, OUT_DIR, name), content);
  console.log(`wrote ${join(OUT_DIR, name)}`);
}
