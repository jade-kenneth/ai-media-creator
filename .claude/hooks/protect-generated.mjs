#!/usr/bin/env node
// PreToolUse hook (Write|Edit|MultiEdit) — refuses edits to generated and
// locked files.
//
// `.skills-source/` is a read-only snapshot, wiped and re-cloned on every sync.
// `AGENTS.md` is generated from it. An edit to either is silently lost on the
// next `pnpm sync-skills`, which is worse than being rejected: the rule
// appears to have been adopted and then disappears.
//
// Durable rules go upstream to the skills-source repository, then regenerate.

import { readFileSync } from 'node:fs';
import { relative, isAbsolute } from 'node:path';

const projectDir = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();

const PROTECTED = [
  {
    test: (path) => path === 'AGENTS.md' || path.endsWith('/AGENTS.md'),
    reason:
      'AGENTS.md is generated from skills-source by scripts/sync-skills.mjs.',
    fix: [
      'Edit conventions/ or skills/ in the skills-source repository, push, then:',
      '  pnpm update-skills --sha <full-sha>',
      'and commit the regenerated AGENTS.md with the updated lock.',
    ],
  },
  {
    test: (path) =>
      path === '.skills-source' || path.startsWith('.skills-source/'),
    reason:
      '.skills-source/ is a read-only snapshot of the locked skills-source revision.',
    fix: [
      'It is wiped and re-cloned on every sync, so this edit would be lost.',
      'Change the upstream file in the skills-source repository instead, then:',
      '  pnpm update-skills --sha <full-sha>',
    ],
  },
  {
    test: (path) =>
      path === 'skills-source.lock.json' || path === 'boilerplate.lock.json',
    reason:
      'Lock file revisions are advanced by their sync scripts, not by hand — a hand-edited lock records a review that never happened.',
    fix: [
      'Use the command that records the review boundary:',
      '  pnpm update-skills --sha <full-sha>      (skills)',
      '  pnpm boilerplate:ack --sha <full-sha>    (boilerplate)',
    ],
  },
  {
    test: (path) => path.startsWith('apps/app-api/src/graphql/generated/'),
    reason: 'GraphQL types are generated by codegen.',
    fix: [
      'Change the SDL and regenerate:',
      '  pnpm --filter app-api generate-graphql-types',
    ],
  },
  {
    test: (path) => path.startsWith('docs/catalogs/'),
    reason:
      'Technical catalogs are generated from source by scripts/generate-catalogs.mjs.',
    fix: [
      'Change the code the catalog describes, then regenerate:',
      '  pnpm catalogs',
    ],
  },
];

function readStdin() {
  try {
    return readFileSync(0, 'utf8');
  } catch {
    return '';
  }
}

function toRepoRelative(filePath) {
  if (!filePath) return '';

  const normalized = isAbsolute(filePath)
    ? relative(projectDir, filePath)
    : filePath;

  return normalized.split('\\').join('/');
}

function main() {
  let input = {};

  try {
    input = JSON.parse(readStdin() || '{}');
  } catch {
    process.exit(0);
  }

  const filePath = toRepoRelative(
    input?.tool_input?.file_path ?? input?.tool_input?.path ?? '',
  );

  if (!filePath || filePath.startsWith('..')) {
    process.exit(0);
  }

  const match = PROTECTED.find((rule) => rule.test(filePath));

  if (!match) {
    process.exit(0);
  }

  process.stderr.write(
    [
      `Refused: ${filePath} is generated or locked.`,
      '',
      match.reason,
      '',
      ...match.fix,
    ].join('\n'),
  );

  process.exit(2);
}

main();
